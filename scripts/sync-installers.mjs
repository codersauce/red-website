import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const manifestPath = join(root, "public", "installers.json");
const argumentsList = process.argv.slice(2);
const check = argumentsList.includes("--check");

function argument(name) {
  const index = argumentsList.indexOf(name);
  return index === -1 ? undefined : argumentsList[index + 1];
}

async function existingManifest() {
  try {
    return JSON.parse(await readFile(manifestPath, "utf8"));
  } catch {
    return null;
  }
}

const previous = await existingManifest();
const sourceCommit = argument("--ref") ?? previous?.sourceCommit;
if (!sourceCommit) {
  throw new Error("Pass --ref <red commit> when syncing installers for the first time.");
}

const sourceDir = argument("--source-dir");
const rawBase = `https://raw.githubusercontent.com/codersauce/red/${sourceCommit}`;

async function sourceFile(path) {
  if (sourceDir) {
    return readFile(join(sourceDir, path), "utf8");
  }
  const response = await fetch(`${rawBase}/${path}`);
  if (!response.ok) {
    throw new Error(`Could not fetch ${path} at ${sourceCommit}: HTTP ${response.status}`);
  }
  return response.text();
}

const [shell, powershell, cargoToml] = await Promise.all([
  sourceFile("install/install.sh"),
  sourceFile("install/install.ps1"),
  sourceFile("Cargo.toml"),
]);
const versionMatch = cargoToml.match(/^version = "([^"]+)"/m);
if (!versionMatch) {
  throw new Error("Could not read Red's package version from Cargo.toml.");
}

const version = versionMatch[1];
const hash = (contents) => createHash("sha256").update(contents).digest("hex");
const manifest = {
  schemaVersion: 1,
  source: "codersauce/red",
  sourceCommit,
  version,
  files: {
    "install.sh": hash(shell),
    "install.ps1": hash(powershell),
  },
};
const manifestContents = `${JSON.stringify(manifest, null, 2)}\n`;
const generatedContents = [
  "// Generated by scripts/sync-installers.mjs. Do not edit.",
  `export const releaseVersion = "v${version}";`,
  `export const installerSourceCommit = "${sourceCommit}";`,
  "",
].join("\n");

const outputs = new Map([
  [join(root, "public", "install.sh"), shell],
  [join(root, "public", "install.ps1"), powershell],
  [manifestPath, manifestContents],
  [join(root, "app", "installers.generated.ts"), generatedContents],
]);

if (check) {
  const drift = [];
  for (const [path, expected] of outputs) {
    let actual;
    try {
      actual = await readFile(path, "utf8");
    } catch {
      actual = null;
    }
    if (actual !== expected) drift.push(path.slice(root.length + 1));
  }
  if (drift.length) {
    throw new Error(`Installer sync is stale: ${drift.join(", ")}`);
  }
  console.log(`Installers match codersauce/red@${sourceCommit}.`);
} else {
  for (const [path, contents] of outputs) {
    await writeFile(path, contents);
  }
  console.log(`Synced Red v${version} installers from ${sourceCommit}.`);
}
