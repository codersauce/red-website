import Negotiator from "negotiator";
import { docManifest } from "../app/docs/manifest";
import { canonicalOrigin } from "../app/public-origin";
import { handleMarkdownRequest, type DocumentationAssets } from "./docs-markdown";

const documentationPaths = new Set<string>(docManifest.map((page) => page.href));
const htmlType = "text/html; charset=utf-8";
const markdownType = "text/markdown; charset=utf-8";

// These headers identify framework requests, which must reach Vinext. Include
// every bypass dimension in Vary as well as any dimensions Vinext already adds.
const frameworkHeaders = [
  "RSC",
  "Next-Router-State-Tree",
  "Next-Router-Prefetch",
  "Next-Router-Segment-Prefetch",
  "Next-Url",
  "Next-Hmr-Refresh",
  "X-Vinext-Interception-Context",
  "X-Vinext-Mounted-Slots",
  "X-Vinext-Rsc-Render-Mode",
  "X-Rsc-Action",
  "Next-Action",
];

async function documentationResponse(request: Request, response: Response): Promise<Response> {
  const headers = new Headers(response.headers);
  const vary = new Map((headers.get("Vary") ?? "").split(",").map((name) => name.trim()).filter(Boolean).map((name) => [name.toLowerCase(), name]));
  if (!vary.has("*")) {
    for (const name of ["Accept", ...frameworkHeaders]) {
      if (!vary.has(name.toLowerCase())) vary.set(name.toLowerCase(), name);
    }
    headers.set("Vary", [...vary.values()].join(", "));
  }
  // Explicit .md URLs remain cacheable. Canonical URLs never share an edge
  // cache entry across HTML, Markdown, or framework request variants.
  headers.set("Cache-Control", "no-store, must-revalidate");
  if (request.method === "HEAD") await response.body?.cancel();
  return new Response(request.method === "HEAD" ? null : response.body, { status: response.status, headers });
}

/** Negotiate only public documentation GET/HEAD requests, using generated bytes. */
export async function handleDocumentationNegotiation(
  request: Request,
  assets: DocumentationAssets,
  renderHtml: () => Promise<Response>,
): Promise<Response | null> {
  const url = new URL(request.url);
  const canonicalPath = url.pathname.replace(/\/$/, "");
  if (!documentationPaths.has(canonicalPath) || (request.method !== "GET" && request.method !== "HEAD")) return null;

  const accept = request.headers.get("Accept");
  const negotiator = new Negotiator({ headers: { accept: accept ?? undefined } });
  const frameworkRequest = url.searchParams.has("_rsc")
    || frameworkHeaders.some((name) => request.headers.has(name))
    || negotiator.mediaTypes().some((type) => type.toLowerCase() === "text/x-component");
  if (frameworkRequest) return documentationResponse(request, await renderHtml());

  if (url.pathname !== canonicalPath) {
    return documentationResponse(request, new Response(null, { status: 308, headers: { Location: canonicalPath + url.search } }));
  }

  // Negotiator ranks quality, specificity, then client order. Server order
  // chooses HTML for missing Accept and ties matched by the same wildcard.
  const representation = negotiator.mediaType([htmlType, markdownType]);
  if (representation === htmlType) return documentationResponse(request, await renderHtml());
  if (representation === markdownType) {
    url.pathname += ".md";
    const response = await handleMarkdownRequest(new Request(url, request), assets);
    if (response) return documentationResponse(request, response);
  }

  return documentationResponse(request, new Response(
    `This page is available as text/html or text/markdown.\nMarkdown: ${canonicalOrigin}${canonicalPath}.md\n`,
    { status: 406, headers: { "Content-Type": "text/plain; charset=utf-8" } },
  ));
}
